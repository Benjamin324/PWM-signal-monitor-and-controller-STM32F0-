void oled_Write_Data( unsigned char data )
{
     // make PB8 = CS# = 1
    GPIOB->BSRR |= GPIO_BSRR_BS_8;
     // make PB9 = D/C# = 1
    GPIOB->BSRR |= GPIO_BSRR_BS_9;
     // make PB8 = CS# = 0
    GPIOB->BSRR |= GPIO_BSRR_BR_8;
    oled_Write( data );
     // make PB8 = CS# = 1
    GPIOB->BSRR |= GPIO_BSRR_BS_8;
    


}

