//Purpose: Send a COMMAND BITS
//Registers/Peripherals accessed: SPI2,GPIOB
void oled_Write_Cmd( unsigned char cmd )
{
    // make PB8 = CS# = 1
    GPIOB->BSRR |= GPIO_BSRR_BS_8;
     // make PB9 = D/C# = 0
    GPIOB->BSRR |= GPIO_BSRR_BR_9;
// make PB8 = CS# = 0
    GPIOB->BSRR |= GPIO_BSRR_BR_8;
    oled_Write( cmd );
     // make PB8 = CS# = 1
     GPIOB->BSRR |= GPIO_BSRR_BS_8;
    


}
