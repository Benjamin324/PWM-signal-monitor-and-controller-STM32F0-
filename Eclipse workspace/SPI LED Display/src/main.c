//Purpose: Manufacterer recommended startup procedure for SSD1306 OLED
//Registers/Peripherals accessed: GPIOB11, SPI2
void led_Startup_Config(void){
	//Drive PB11 low. GPIOB->BSSR = 1
    GPIOB->BSRR |= GPIO_BSRR_BR_11;
	//Run a 40k for loop iteration or implement a 10ms timer
    for(int i = 0; i < 40000; i++){}
	//Drive PB11 high GPIOB->IDR11 = 1
    GPIOB->ODR = GPIO_ODR_11;
	//Run a 40k for loop iteration or implement a 10ms timer
     for(int i = 0; i < 40000; i++){}
	//Send initialization commands to LED Display
    for ( unsigned int i = 0; i < sizeof( oled_init_cmds ); i++ )
    {
        oled_Write_Cmd( oled_init_cmds[i] );
    }
    //Change d/c# to 1 for data (PB9)
    GPIOB->BSRR = GPIO_BSRR_BS_9;
	//Fill LED Display data memory (GDDRAM) with zeros:
   /* - for each PAGE = 0, 1, ..., 7
        set starting SEG = 0
        call oled_Write_Data( 0x00 ) 128 times
    */

   for(unsigned int PAGE = 0; PAGE <= 7; PAGE++){
	   oled_Write_Cmd(0xB0+PAGE);
	   oled_Write_Cmd(0x00);
	   oled_Write_Cmd(0x10);
        for(unsigned int SEG = 0; SEG <= 127; SEG++){
            oled_Write_Data(0x00);
        }
   }


}
